        static StandardSpecimen[] standards = null;

        static StandardDataBase()
        {
            List<StandardSpecimen> list = new List<StandardSpecimen>();

            StandardSpecimen specimen = null;
            for (int i = 0; i < spectrums.Length; i++)
            {
                Spectrum spectrum = new Spectrum(new WavelengthRange(400, 700, 10));
                for (int j = 0; j < 31; j++)
                    spectrum.Data[j] = spectrums[i][j] / 100.0;

                if (i % 2 == 0)
                {
                    specimen = new StandardSpecimen();
                    specimen.MeasurementCaliber = Optical.MeasurementCaliber.Phi4;
                    specimen.SCI = new ColorData(spectrum);
                    if (i == 0)
                    {
                        list.Add(specimen);
                        specimen = new StandardSpecimen();
                        specimen.MeasurementCaliber = Optical.MeasurementCaliber.Phi4;
                    }
                }
                else
                {
                    specimen.SCE = new ColorData(spectrum);
                    list.Add(specimen);
                    specimen = null;
                }
            }

            Formula formula = new Formula(Optical.StandardIlluminant.D65, Optical.StandardObserver.CIE1964);

            for (int i = 0; i < labs.Length; i++)
            {
                ColorData color = new ColorData();
                color.Set(formula.Observer, formula.Illuminant, formula.LabToXyz(labs[i]));

                if (i % 2 == 0)
                {
                    specimen = new StandardSpecimen();
                    specimen.MeasurementCaliber = Optical.MeasurementCaliber.Phi4;
                    specimen.SCI = color;
                    if (i == 0)
                    {
                        list.Add(specimen);
                        specimen = new StandardSpecimen();
                        specimen.MeasurementCaliber = Optical.MeasurementCaliber.Phi4;
                    }
                }
                else
                {
                    specimen.SCE = color;
                    list.Add(specimen);
                    specimen = null;
                }
            }

            standards = list.ToArray();
        }

        public static StandardSpecimen[] Standards
        {
            get { return standards; }
        }
