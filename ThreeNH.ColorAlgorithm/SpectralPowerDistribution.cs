            }

            _range = range;
            _distribution = new double[distribution.Length];
            Array.Copy(distribution, _distribution, _distribution.Length);
        }

        public double this[int wavelength]
        {
            get
            {
                return _distribution[_range.IndexOf(wavelength)];
            }
        }

        public double GetValueByIndex(int index)
        {
            return _distribution[index];
        }

        public WavelengthRange Range { get { return _range; } }
    }
