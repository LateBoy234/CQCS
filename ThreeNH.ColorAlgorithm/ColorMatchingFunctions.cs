        static readonly ColorMatchingFunctions _cie1937;
        static readonly ColorMatchingFunctions _cie1964;

        static ColorMatchingFunctions()
        {
            ColorMatchingFunction[] functions = new ColorMatchingFunction[CIE1931MatchingFunctionsData.GetLength(0)];
            for (int i = 0; i < functions.Length; i++)
            {
                functions[i] = new ColorMatchingFunction
                {
                    x = CIE1931MatchingFunctionsData[i, 0],
                    y = CIE1931MatchingFunctionsData[i, 1],
                    z = CIE1931MatchingFunctionsData[i, 2]
                };
            }
            _cie1937 = new ColorMatchingFunctions(new WavelengthRange(380, 780, 5), functions);

            functions = new ColorMatchingFunction[CIE1964MatchingFunctionsData.GetLength(0)];
            for (int i = 0; i < functions.Length; i++)
            {
                functions[i] = new ColorMatchingFunction
                {
                    x = CIE1964MatchingFunctionsData[i, 0],
                    y = CIE1964MatchingFunctionsData[i, 1],
                    z = CIE1964MatchingFunctionsData[i, 2]
                };
            }
            _cie1964 = new ColorMatchingFunctions(new WavelengthRange(380, 780, 5), functions);
        }

        public static ColorMatchingFunctions GetByObserver(StandardObserver observer)
        {
            if (observer == StandardObserver.CIE1931)
                return _cie1937;
            else if (observer == StandardObserver.CIE1964)
                return _cie1964;
            else
                return null;
        }

        private ColorMatchingFunction[] _functions;

        private ColorMatchingFunctions(WavelengthRange range, ColorMatchingFunction[] functions)
        {
            if (range.Count != functions.Length)
            {
                throw new ArgumentException("range.Count not equals functions.Length");
            }

            Range = range;
            _functions = functions;
        }

        public WavelengthRange Range { get; private set; }
        public ColorMatchingFunction this[int wavelength]
        {
            get { return _functions[Range.IndexOf(wavelength)]; }
        }
